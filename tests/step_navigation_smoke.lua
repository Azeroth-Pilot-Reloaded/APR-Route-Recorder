local E = AprRC.routeEditor
local route = assert(AprRC.editorModel:NewRoute("Step navigation"))
for index = 1, 45 do route.steps[index] = { Note = "Step " .. index } end
route.parallelSteps = { { conditions = {}, steps = { { Note = "First" }, { Note = "Last" } } } }
E:Show(); E:SelectRoute(route.name); E:SelectTab("steps")
assert(E.stepPrevious.disabled and not E.stepNext.disabled)
E.stepNext:Fire("OnClick")
assert(E.session.selected == 2 and not E.session:IsDirty())
E:SelectStep(40)
E.stepNext:Fire("OnClick")
assert(E.session.selected == 41 and E.page == 2)
E.stepPrevious:Fire("OnClick")
assert(E.session.selected == 40 and E.page == 1)
E:SelectStep(45)
assert(E.stepNext.disabled)
assert(not E:SelectStep(46) and E.session.selected == 45)
local _, _, anchor, offset = E.stepNext.frame:GetPoint()
assert(anchor == "TOPRIGHT" and offset == 0)
E:ToggleCompact(); E:ShowStepPane("inspector")
E.stepPrevious:Fire("OnClick")
assert(E.session.selected == 44 and E.compactPane == "inspector")
E:SelectTab("parallel")
assert(E.stepPrevious.disabled)
E.stepNext:Fire("OnClick")
assert(E.session.parallelSelected == 2 and E.stepNext.disabled and E.session.selected == 44)
E:ToggleCompact()
TestCloseWorkshop()
assert(#UIErrors == 0, table.concat(UIErrors, "\n"))
print("Inspector navigation: boundaries, page transitions, compact and parallel steps passed.")
